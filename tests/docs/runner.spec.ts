  await page.keyboard.type("import { parseOsu } from 'osu-files'\nimport fs from 'node:fs'\n\nconst value = parseOsu(beatmaps[0].osuText).metadta")
  await expect(example.locator('.api-example__diagnostics')).toContainText("Property 'metadta' does not exist")
